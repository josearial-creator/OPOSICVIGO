const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH==='bundled'?undefined:(process.env.CHROMIUM_PATH||'/usr/bin/chromium'),args:['--no-sandbox'],headless:true});
 try{
  const page=await browser.newPage({viewport:{width:390,height:844}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.route('https://raw.githubusercontent.com/**',r=>r.fulfill({json:[]}));
  await page.goto('http://127.0.0.1:8086/#mi-espacio');
  await page.locator('#mi-espacio').waitFor({state:'visible'});
  assert.equal(await page.locator('#historial-rumbo').isVisible(),false);
  assert.equal(await page.locator('#mi-evolucion').isVisible(),false);
  assert.equal(await page.locator('#mi-dia').isVisible(),false);
  assert.equal(await page.locator('.rumbo-section-nav a').count(),6);
  assert.equal(await page.locator('.rumbo-section-nav a[aria-current="page"]').getAttribute('href'),'#mi-espacio');
  assert.equal(await page.locator('.mobile-tabbar [data-mobile-tab="diario"]').getAttribute('href'),'#mi-espacio');
  const oldData=await page.evaluate(()=>({...localStorage}));
  await page.locator('.rumbo-section-nav a[href="#historial-rumbo"]').click();
  await page.locator('#historial-rumbo').waitFor({state:'visible'});
  assert.equal(await page.locator('#mi-espacio').isVisible(),false);
  assert.equal(await page.locator('#mi-evolucion').isVisible(),false);
  assert.equal(await page.evaluate(()=>location.hash),'#historial-rumbo');
  await page.locator('.rumbo-section-nav a[href="#ev-diary"]').click();
  await page.locator('#ev-diary').waitFor({state:'visible'});
  assert.equal(await page.locator('#ev-training').isVisible(),false);
  assert.equal(await page.locator('#mi-espacio').isVisible(),false);
  assert.equal(await page.locator('.ev-metrics').isVisible(),false);
  await page.locator('.rumbo-section-nav a[href="#ev-training"]').click();
  await page.locator('#ev-training').waitFor({state:'visible'});
  assert.equal(await page.locator('#ev-diary').isVisible(),false);
  await page.locator('.rumbo-section-nav a[href="#mi-evolucion"]').click();
  await page.locator('.ev-metrics').waitFor({state:'visible'});
  assert.equal(await page.locator('#ev-diary').isVisible(),false);
  assert.equal(await page.locator('#ev-training').isVisible(),false);
  await page.locator('.mobile-tabbar [data-mobile-tab="oposiciones"]').click();
  await page.locator('#convocatorias').waitFor({state:'visible'});
  assert.equal(await page.locator('#mi-evolucion').isVisible(),false);
  await page.locator('.rumbo-section-nav a[href="#apuntes-estudio"]').click();
  await page.locator('#apuntes-estudio').waitFor({state:'visible'});
  assert.equal(await page.locator('#convocatorias').isVisible(),false);
  await page.locator('.rumbo-section-nav a[href="#favoritos"]').click();
  await page.locator('#convocatorias').waitFor({state:'visible'});
  assert.equal(await page.locator('#only-favs').isChecked(),true);
  await page.locator('.mobile-tabbar [data-mobile-tab="mas"]').click();
  await page.locator('#productividad').waitFor({state:'visible'});
  assert.equal(await page.locator('#proyectos').isVisible(),false);
  await page.locator('#rumbo-settings-open').click();await page.locator('[data-settings-route="copias-rumbo"]').click();
  await page.locator('#copias-rumbo').waitFor({state:'visible'});
  assert.equal(await page.locator('#productividad').isVisible(),false);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Sin desbordamiento horizontal en móvil');
  assert.deepEqual(await page.evaluate(()=>({...localStorage})),oldData,'Navegar no debe cambiar datos locales');
  await page.setViewportSize({width:1120,height:850});
  await page.locator('.sidebar a[href="#mi-dia"]').click();
  await page.locator('#mi-dia').waitFor({state:'visible'});
  assert.equal(await page.locator('#copias-rumbo').isVisible(),false,'Escritorio también tiene apartados independientes');
  assert.equal(await page.locator('#convocatorias').isVisible(),false);
  await page.goto('http://127.0.0.1:8086/#historial-rumbo');
  await page.locator('#historial-rumbo').waitFor({state:'visible'});
  assert.equal(await page.locator('#mi-espacio').isVisible(),false,'Enlace directo abre solo su pantalla');
  assert.deepEqual(errors,[]);
  console.log('PASS: apartados independientes, anclas, móvil/escritorio y datos intactos.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
