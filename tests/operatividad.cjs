const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const base='http://127.0.0.1:8086/';
const feed=[{puesto:'Auxiliar de prueba',organismo:'Concello sintético',grupo:'C2',plazas:2,fuente:'https://example.test/a'},{puesto:'Administrativo de prueba',organismo:'Concello sintético',grupo:'C1',plazas:1,fuente:'https://example.test/b'}];
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH==='bundled'?undefined:(process.env.CHROMIUM_PATH||'/usr/bin/chromium'),headless:true,args:['--no-sandbox']});
 try{
  for(const width of [390,1120]){
   const context=await browser.newContext({viewport:{width,height:840},serviceWorkers:'block'});
   const page=await context.newPage(), errors=[];
   page.on('pageerror',e=>errors.push(e.message));
   await page.route('https://raw.githubusercontent.com/**',route=>route.fulfill({json:feed}));
   await page.goto(base+'#mi-dia');
   const action=page.locator('#assistant-focus-next');
   assert.equal(await action.isDisabled(),true,'Sin tarea no hay bloque');
   await page.locator('#assistant-capture input').fill('Repasar legislación');
   await page.locator('#assistant-capture button[type=submit]').click();
   assert.equal(await action.isEnabled(),true);
   // Guardado del siguiente paso visible, persistente y unido a la tarea activa.
   const stepInput=page.locator('#assistant-step-input');
   await stepInput.fill('Abrir el tema 3 y leer el primer apartado');
   await page.locator('#assistant-step-save').click();
   assert.equal(await page.locator('#assistant-step-status').innerText(),'Siguiente paso guardado.');
   const firstStep=await page.evaluate(()=>JSON.parse(localStorage.getItem('rumbo-asistente-v1')).items[0].nextStep);
   assert.equal(firstStep,'Abrir el tema 3 y leer el primer apartado');
   await page.reload();
   assert.equal(await stepInput.inputValue(),firstStep,'El paso persiste al recargar');
   await page.locator('.assistant-inbox-details summary').click();
   await page.locator('#assistant-inbox').getByRole('button',{name:'Priorizar'}).first().click();
   await action.click();await page.locator('#productividad').waitFor({state:'visible'});
   assert.match(await page.locator('#assistant-task-hint').innerText(),/Abrir el tema 3 y leer el primer apartado/,'El paso acompaña al temporizador');
   assert.equal(await page.locator('#assistant-timer-title').inputValue(),'Repasar legislación');
   assert.equal(await page.locator('#assistant-duration').inputValue(),'10');
   assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('rumbo-asistente-v1')).timer),null,'Preparar no inicia sin consentimiento');
   await page.locator('#assistant-start').click();
   assert.equal(await page.locator('#assistant-start').isDisabled(),true,'Evitar sesiones simultáneas');
   await page.locator('#assistant-pause').click();
   await page.goto(base+'#proyectos');
   await page.locator('#org-new-project').evaluate(el=>el.open=true);
   await page.locator('#org-project-form [name=name]').fill('Proyecto concluido');
   await page.locator('#org-project-form [name=next]').fill('Acción ya terminada');
   await page.locator('#org-project-form button[type=submit]').click();
   await page.locator('#org-projects').getByRole('button',{name:'Terminar',exact:true}).click();
   await page.goto(base+'#productividad');
   assert.equal((await page.locator('#assistant-project option').allTextContents()).includes('Proyecto concluido'),false,'No ofrecer proyectos terminados');
   await page.goto(base+'#convocatorias');
   await page.locator('#rows tr').first().waitFor({state:'attached'});
   const star=page.locator('#rows tr').first().getByRole('button',{name:'Alternar favorito'});
   await star.focus();await page.keyboard.press('Enter');
   assert.equal(await page.locator('#rows tr').first().getByRole('button',{name:'Alternar favorito'}).getAttribute('aria-pressed'),'true');
   assert.equal(await page.evaluate(()=>document.activeElement?.getAttribute('aria-label')),'Alternar favorito','Foco después del render');
   const before=await page.evaluate(()=>localStorage.getItem('rumbo-asistente-v1'));
   await page.goto(base+'#mi-dia');await page.locator('#assistant-focus-next').click();await page.locator('#productividad').waitFor({state:'visible'});
   assert.equal(await page.evaluate(()=>localStorage.getItem('rumbo-asistente-v1')),before,'Preparar bloque no escribe');
   assert.deepEqual(errors,[]);
   const second=await context.newPage();
   await second.route('https://raw.githubusercontent.com/**',route=>route.fulfill({json:feed}));
   await page.goto(base+'#mi-dia');await second.goto(base+'#mi-dia');
   await page.locator('#assistant-capture input').fill('Tarea de primera pestaña');
   await page.locator('#assistant-capture button[type=submit]').click();
   await second.locator('#assistant-capture input').fill('Tarea obsoleta de segunda pestaña');
   await second.locator('#assistant-capture button[type=submit]').click();
   const current=await page.evaluate(()=>JSON.parse(localStorage.getItem('rumbo-asistente-v1')));
   assert.equal(current.items.some(x=>x.text==='Tarea de primera pestaña'),true);
   assert.equal(current.items.some(x=>x.text==='Tarea obsoleta de segunda pestaña'),false);
   assert.match(await second.locator('#assistant-message').innerText(),/otra pestaña/i);
   await second.close();
   // Proyectos: una pestaña antigua tampoco puede sobrescribir un alta reciente.
   const other=await context.newPage();
   await other.route('https://raw.githubusercontent.com/**',route=>route.fulfill({json:feed}));
   await page.goto(base+'#proyectos');await other.goto(base+'#proyectos');
   await page.locator('#org-new-project').evaluate(el=>el.open=true);
   await other.locator('#org-new-project').evaluate(el=>el.open=true);
   await page.locator('#org-project-form [name=name]').fill('Proyecto actual');
   await page.locator('#org-project-form button[type=submit]').click();
   await other.locator('#org-project-form [name=name]').fill('Proyecto obsoleto');
   await other.locator('#org-project-form button[type=submit]').click();
   const currentProjects=await page.evaluate(()=>JSON.parse(localStorage.getItem('rumbo-organizacion-v1')));
   assert.equal(currentProjects.projects.some(x=>x.name==='Proyecto actual'),true);
   assert.equal(currentProjects.projects.some(x=>x.name==='Proyecto obsoleto'),false);
   assert.match(await other.locator('#org-status').innerText(),/otra pestaña/i);
   await other.close();await context.close();
   // Texto largo: la sesión mantiene el identificador completo de la tarea.
   const isolated=await browser.newContext({viewport:{width,height:840},serviceWorkers:'block'});
   const longPage=await isolated.newPage();
   await longPage.route('https://raw.githubusercontent.com/**',route=>route.fulfill({json:feed}));
   await longPage.goto(base+'#mi-dia');
   const longTitle='Preparar una tarea extensa con detalles y requisitos concretos '.repeat(3);
   await longPage.locator('#assistant-capture input').fill(longTitle);
   await longPage.locator('#assistant-capture button[type=submit]').click();
   const original=await longPage.evaluate(()=>JSON.parse(localStorage.getItem('rumbo-asistente-v1')).items[0].id);
   await longPage.locator('#assistant-focus-next').click();
   await longPage.locator('#assistant-start').click();
   const linked=await longPage.evaluate(()=>JSON.parse(localStorage.getItem('rumbo-asistente-v1')).timer.taskId);
   assert.equal(linked,original,'La tarea conserva su relación aunque el título visual sea abreviado');
   await isolated.close();
   // Inicio rápido: un gesto inicia el foco de 10 minutos sin crear duplicados.
   const fastContext=await browser.newContext({viewport:{width,height:840},serviceWorkers:'block'});
   const fastPage=await fastContext.newPage(),fastErrors=[];
   fastPage.on('pageerror',e=>fastErrors.push(e.message));
   await fastPage.route('https://raw.githubusercontent.com/**',route=>route.fulfill({json:feed}));
   await fastPage.goto(base+'#mi-dia');
   const quick=fastPage.locator('#assistant-quick-start');
   assert.equal(await quick.isDisabled(),true,'Sin tarea no se puede iniciar');
   await fastPage.locator('#assistant-capture input').fill('Revisar una convocatoria');
   await fastPage.locator('#assistant-capture button[type=submit]').click();
   assert.equal(await quick.isEnabled(),true,'Una tarea permite inicio rápido');
   const expectedId=await fastPage.evaluate(()=>JSON.parse(localStorage.getItem('rumbo-asistente-v1')).items[0].id);
   await quick.click();
   await fastPage.locator('#productividad').waitFor({state:'visible'});
   const quickTimer=await fastPage.evaluate(()=>JSON.parse(localStorage.getItem('rumbo-asistente-v1')).timer);
   assert.equal(quickTimer.target,600,'El bloque rápido dura 10 minutos');
   assert.equal(quickTimer.taskId,expectedId,'El bloque mantiene la asociación a la tarea');
   assert.equal(quickTimer.title,'Revisar una convocatoria');
   assert.ok(quickTimer.startedAt!==null,'El temporizador se inicia realmente');
   await fastPage.goto(base+'#mi-dia');
   assert.equal(await quick.isDisabled(),true,'No inicia otro bloque simultáneo');
   await fastPage.locator('#assistant-focus-next').click();
   await fastPage.locator('#assistant-pause').click();
   const pausedTimer=await fastPage.evaluate(()=>JSON.parse(localStorage.getItem('rumbo-asistente-v1')).timer);
   assert.equal(pausedTimer.startedAt,null,'Pausar no pierde el bloque');
   assert.deepEqual(fastErrors,[]);
   await fastContext.close();
  }
  console.log('PASS: inicio de foco, filtro de proyectos, favoritos con teclado y conflicto entre pestañas.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
