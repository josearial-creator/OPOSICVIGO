const {chromium}=require('playwright'),assert=require('node:assert/strict'),fs=require('node:fs/promises');
(async()=>{
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH==='bundled'?undefined:(process.env.CHROMIUM_PATH||'/usr/bin/chromium'),args:['--no-sandbox'],headless:true});
try{
const page=await browser.newPage({viewport:{width:390,height:844},acceptDownloads:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.route('https://raw.githubusercontent.com/**',r=>r.fulfill({json:[{puesto:'Auxiliar',organismo:'Vigo',plazas:3,grupo:'C2',fin:'30/11/2026',inscripcion:'Por verificar'}]}));
await page.goto('http://127.0.0.1:8086/');
await page.locator('#rows tr').first().waitFor({state:'attached'});
assert.equal(await page.locator('.mobile-tabbar a').count(),4);
assert.equal(await page.locator('#mi-dia').isVisible(),true);
assert.match(await page.locator('.hero-line h1').innerText(),/Todo lo importante/);
assert.equal(await page.locator('.quick-action').count(),3);
assert.equal(await page.locator('link[href="redisenio.css"]').count(),1);
assert.equal(await page.locator('.hero-line').evaluate(el=>getComputedStyle(el).backgroundImage.includes('linear-gradient')),true);
await page.locator('[data-mobile-tab="oposiciones"]').click();
await page.locator('#convocatorias').waitFor({state:'visible'});
assert.equal(await page.locator('#mi-dia').isVisible(),false);
assert.equal(await page.locator('#rows tr').first().getAttribute('data-test')||'','');
assert.equal(await page.locator('#rows td[data-label="Fin del plazo"]').first().innerText(),'30/11/2026');
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
await page.getByRole('button',{name:'Alternar favorito'}).click();
await page.getByRole('button',{name:'Detalle',exact:true}).click();
await page.locator('#dialog-content textarea').fill('Nota para restaurar');
await page.locator('#dialog-done').click();
await page.locator('[data-mobile-tab="diario"]').click();await page.locator('#mi-evolucion').waitFor({state:'visible'});
await page.locator('[data-mobile-tab="mas"]').click();await page.locator('#copias-rumbo').waitFor({state:'visible'});
await page.locator('#backup-pass').fill('frase-muy-segura-123');
await page.locator('#backup-repeat').fill('frase-muy-segura-123');
const download=page.waitForEvent('download');await page.locator('#backup-export').click();
const file=await download;assert.match(file.suggestedFilename(),/rumbo-copia-cifrada/);
assert.equal(await page.locator('#backup-status').innerText(),'Copia cifrada creada. Guarda el archivo y la frase por separado.');
const saved=await fs.readFile(await file.path(),'utf8');
assert.equal(saved.includes('Auxiliar'),false);
await page.locator('#backup-file').setInputFiles({name:'copia.json',mimeType:'application/json',buffer:Buffer.from(saved)});
await page.locator('#backup-pass').fill('contrasena-equivocada');
await page.locator('#backup-import').click();
await page.getByText(/No se recuperó la copia/).waitFor();
await page.locator('#backup-pass').fill('frase-muy-segura-123');
page.once('dialog',dialog=>dialog.dismiss());
await page.locator('#backup-import').click();
await page.getByText(/Recuperación cancelada sin cambios/).waitFor();
await page.evaluate(()=>{const v=JSON.parse(localStorage.getItem('rumbo-replica-v1'));v.notes['marcador-prueba']='Temporal';localStorage.setItem('rumbo-replica-v1',JSON.stringify(v));});
page.once('dialog',dialog=>dialog.accept());
await Promise.all([page.waitForNavigation({waitUntil:'load'}),page.locator('#backup-import').click()]);
assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('rumbo-replica-v1')).notes['marcador-prueba']||null),null);
const restored=await page.evaluate(()=>JSON.parse(localStorage.getItem('rumbo-replica-v1')));
assert.equal(restored.favorites.length,1);assert.deepEqual(Object.values(restored.notes),['Nota para restaurar']);
const manifest=await page.locator('link[rel=manifest]').getAttribute('href');assert.equal(manifest,'manifest.webmanifest');
const resp=await page.request.get('http://127.0.0.1:8086/sw.js');assert.equal(resp.status(),200);
assert.deepEqual(errors,[]);
console.log('PASS: navegación móvil, tarjetas, copias cifradas y archivos PWA.');
}finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});