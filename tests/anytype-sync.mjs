import assert from 'node:assert/strict';
import worker from '../rumbo-worker/worker.mjs';
const origin='https://example.test', sync='s'.repeat(40), access='a'.repeat(40);
import {DatabaseSync} from 'node:sqlite';
import {readFileSync} from 'node:fs';
const sql=new DatabaseSync(':memory:');
sql.exec(readFileSync(new URL('../rumbo-worker/anytype-schema.sql',import.meta.url),'utf8'));
const db={
 prepare(query){const run=(...args)=>({meta:{changes:Number(sql.prepare(query).run(...args).changes)}});return {run:()=>run(),all:async()=>({results:sql.prepare(query).all()}),bind(...args){return {run:()=>run(...args),first:async()=>sql.prepare(query).get(...args)||null}}};},
 async batch(statements){sql.exec('BEGIN');try{const results=statements.map(s=>s.run());sql.exec('COMMIT');return results;}catch(e){sql.exec('ROLLBACK');throw e;}}
};
const env={ALLOWED_ORIGIN:origin,RUMBO_ACCESS_TOKEN:access,ANYTYPE_SYNC_TOKEN:sync,db};
const url='https://worker.test/anytype/tasks';
const task={id:'bafy'+'a'.repeat(50),titulo:'Tarea ficticia',estado:'pendiente',fecha_modificacion:'2026-11-26T09:00:00Z'};
const post=(token,t)=>worker.fetch(new Request(url,{method:'POST',headers:{Authorization:'Bearer '+token,'Content-Type':'application/json'},body:JSON.stringify({origen:'anytype',total:1,tareas:[t]})}),env);
const get=()=>worker.fetch(new Request(url,{headers:{Origin:origin,Authorization:'Bearer '+access}}),env);
assert.equal((await post(access,task)).status,401);
assert.equal((await post(sync,task)).status,200);
assert.equal((await post(sync,task)).status,200);
assert.equal((await (await get()).json()).total,1);
assert.equal((await post(sync,{...task,estado:'completada'})).status,200);
assert.equal((await (await get()).json()).tareas[0].activa,false);
assert.equal((await post(sync,{...task,titulo:''})).status,400);
assert.equal((await post(sync,{...task,estado:'por_revisar'})).status,200);
assert.equal((await (await get()).json()).tareas[0].activa,false);
assert.equal((await worker.fetch(new Request(url,{headers:{Origin:origin,Authorization:'Bearer '+sync}}),env)).status,401);
assert.equal((await post(sync,{...task,estado:'pendiente',fecha_modificacion:'2026-01-01T00:00:00Z'})).status,200);
assert.equal((await (await get()).json()).tareas[0].estado,'por_revisar');
const second={...task,id:'bafy'+'b'.repeat(50)};
await Promise.all([post(sync,second),post(sync,{...task,estado:'completada'})]);
assert.equal((await (await get()).json()).total,2);
console.log('Anytype synthetic smoke tests passed');

const calendarToken='c'.repeat(40);
env.CALENDAR_SYNC_TOKEN=calendarToken;
const calendarUrl='https://worker.test/calendar/sync';
const event={source:'google-calendar',calendar_id:'primary',source_event_id:'fixture-1',title:'Cita ficticia',start:'2026-11-26T11:00:00Z',end:'2026-11-26T12:00:00Z',all_day:false};
const date=new Date(Date.now()-2000).toISOString();
const calendarPost=(token,events,captured=date,extra={})=>worker.fetch(new Request(calendarUrl,{method:'POST',headers:{Authorization:'Bearer '+token,'Content-Type':'application/json',...extra},body:JSON.stringify({captured_at:captured,count:events.length,events})}),env);
assert.equal((await calendarPost(sync,[event])).status,401);
assert.equal((await calendarPost(access,[event])).status,401);
assert.equal((await calendarPost(calendarToken,[event],date,{Origin:origin})).status,404);
assert.equal((await calendarPost(calendarToken,[event,event])).status,422);
assert.deepEqual(await (await calendarPost(calendarToken,[event])).json(),{applied:true,count:1});
assert.deepEqual(await (await calendarPost(calendarToken,[],new Date(Date.now()-3000).toISOString())).json(),{applied:false,count:0});
assert.equal(JSON.parse(sql.prepare('SELECT events_json FROM rumbo_calendar_snapshot').get().events_json).length,1);
assert.deepEqual(await (await calendarPost(calendarToken,[],new Date().toISOString())).json(),{applied:true,count:0});
assert.equal(JSON.parse(sql.prepare('SELECT events_json FROM rumbo_calendar_snapshot').get().events_json).length,0);
assert.equal((await (await get()).json()).total,2);
assert.equal((await post(calendarToken,task)).status,401);
console.log('Calendar and Anytype independent credentials and SQLite snapshot regression passed');

const readAgenda=(token,from=origin,method='GET')=>worker.fetch(new Request('https://worker.test/calendar/events',{method,headers:{Origin:from,Authorization:'Bearer '+token}}),env);
assert.equal((await readAgenda(calendarToken)).status,401);
assert.equal((await readAgenda(sync)).status,401);
assert.equal((await readAgenda(access,'https://unauthorized.invalid')).status,403);
assert.equal((await readAgenda(access,origin,'DELETE')).status,405);
const capturedAt=new Date(Date.now()+1000).toISOString();
assert.equal((await calendarPost(calendarToken,[event],capturedAt)).status,200);
const response=await readAgenda(access);
assert.equal(response.status,200);
assert.equal(response.headers.get('cache-control'),'no-store');
assert.equal(response.headers.get('access-control-allow-origin'),origin);
assert.deepEqual(await response.json(),{captured_at:capturedAt,events:[{id:event.source_event_id,title:event.title,start:event.start,end:event.end,all_day:event.all_day}]});
assert.equal((await (await get()).json()).total,2);
console.log('Private read-only calendar endpoint passes');
